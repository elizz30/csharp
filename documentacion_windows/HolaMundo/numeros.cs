//EXPLORACION DE LOS ENTEROS

void OperacionSencilla()
{

    //SUMA
    int a = 5;
    int b = 3;
    int c = a + b;
    Console.WriteLine(c);

    //RESTA
    int d = a - b;
    Console.WriteLine(d);

    //MULTIPLICACION
    int e = a * b;
    Console.WriteLine(e);

    //DIVISION
    int f = a / b;
    Console.WriteLine(f);

}

