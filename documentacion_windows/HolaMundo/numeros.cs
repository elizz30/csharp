void OperacionMixtas()
{
    int a = 5;
    int b = 3;
    int c = 2;
    int d = a + b * c;
    Console.WriteLine(d);

    int e = (a + b) * c;
    Console.WriteLine(e);

    int f = (a + b) - 6 * c + (12 * 4) / 3 + 12;
    Console.WriteLine(f);

}

